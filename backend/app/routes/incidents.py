"""
Security Incident Management and Detection API Routes
Endpoints:
- GET /api/v1/incidents: Query paginated security incidents with multi-field filters
- GET /api/v1/incidents/{incident_id}: Retrieve single incident by UUID
- PATCH /api/v1/incidents/{incident_id}/status: Transition incident lifecycle status
- GET /api/v1/detection/rules: Inspect registered detection rules and operational status
- GET /api/v1/detection/summary: Aggregated metrics of incidents, severity, and rule distributions

SECURITY NOTICE: In Phase 2 development, incident endpoints are accessible locally.
Production deployment requires role-based access control (RBAC) and OAuth2/JWT authentication.
"""

from typing import Optional, List
from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.orm import Session

from sentinel.backend.app.database import get_db
from sentinel.backend.app.detection.rule_registry import rule_registry
from sentinel.backend.app.schemas.incident import (
    IncidentResponse,
    IncidentStatusUpdate,
    IncidentListResponse,
    DetectionRuleResponse,
    DetectionSummaryResponse
)
from sentinel.backend.app.services.incident_service import (
    get_incident_by_id,
    query_incidents,
    update_incident_status,
    get_detection_summary,
    InvalidStatusTransitionError
)

router = APIRouter(tags=["Security Incidents & Detection"])


@router.get(
    "/api/v1/incidents",
    response_model=IncidentListResponse,
    summary="List security incidents with filtering and pagination",
    description="Retrieve security incidents generated by the deterministic detection engine."
)
def list_incidents(
    status: Optional[str] = Query(None, description="Filter by status (OPEN, INVESTIGATING, RESOLVED, FALSE_POSITIVE)"),
    severity: Optional[str] = Query(None, description="Filter by severity (LOW, MEDIUM, HIGH, CRITICAL)"),
    rule_id: Optional[str] = Query(None, description="Filter by detection rule ID"),
    service_identity: Optional[str] = Query(None, description="Filter by implicated service identity"),
    min_risk_score: Optional[int] = Query(None, ge=0, le=100, description="Minimum risk score"),
    max_risk_score: Optional[int] = Query(None, ge=0, le=100, description="Maximum risk score"),
    page: int = Query(1, ge=1, description="Page number"),
    limit: int = Query(50, ge=1, le=100, description="Items per page"),
    db: Session = Depends(get_db)
):
    """Query paginated security incidents."""
    total, items = query_incidents(
        db=db,
        status=status,
        severity=severity,
        rule_id=rule_id,
        service_identity=service_identity,
        min_risk_score=min_risk_score,
        max_risk_score=max_risk_score,
        page=page,
        limit=limit
    )

    pages = (total + limit - 1) // limit if total > 0 else 0

    return IncidentListResponse(
        total=total,
        page=page,
        limit=limit,
        pages=pages,
        items=items
    )


@router.get(
    "/api/v1/incidents/{incident_id}",
    response_model=IncidentResponse,
    summary="Retrieve single incident by ID",
    description="Fetch comprehensive findings, risk score breakdown, and evidence for a specific incident.",
    responses={
        200: {"description": "Incident found"},
        404: {"description": "Incident not found"}
    }
)
def get_incident(
    incident_id: str,
    db: Session = Depends(get_db)
):
    """Retrieve individual incident by UUID."""
    incident = get_incident_by_id(db, incident_id)
    if not incident:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail={
                "error": "NotFoundError",
                "message": f"Security incident with ID '{incident_id}' was not found.",
                "incident_id": incident_id
            }
        )
    return incident


@router.patch(
    "/api/v1/incidents/{incident_id}/status",
    response_model=IncidentResponse,
    summary="Update incident lifecycle status",
    description="Transition incident between OPEN, INVESTIGATING, RESOLVED, and FALSE_POSITIVE states.",
    responses={
        200: {"description": "Status updated successfully"},
        400: {"description": "Invalid status transition"},
        404: {"description": "Incident not found"}
    }
)
@router.put(
    "/api/v1/incidents/{incident_id}/status",
    response_model=IncidentResponse,
    include_in_schema=False
)
def patch_incident_status(
    incident_id: str,
    update_data: IncidentStatusUpdate,
    db: Session = Depends(get_db)
):
    """Update triage state with strict lifecycle transition validation."""
    try:
        updated = update_incident_status(
            db=db,
            incident_id=incident_id,
            new_status=update_data.status,
            notes=update_data.notes
        )
        return updated
    except InvalidStatusTransitionError as trans_err:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={
                "error": "InvalidStatusTransitionError",
                "message": str(trans_err),
                "incident_id": incident_id
            }
        )
    except ValueError as val_err:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail={
                "error": "NotFoundError",
                "message": str(val_err),
                "incident_id": incident_id
            }
        )


@router.get(
    "/api/v1/detection/rules",
    response_model=List[DetectionRuleResponse],
    summary="List registered detection rules",
    description="Inspect active detection rules, baseline severity, and configuration parameters."
)
def list_detection_rules():
    """Retrieve metadata for all configured security detection rules."""
    rules = rule_registry.list_rules()
    response_list = []
    for r in rules:
        meta = r.get_metadata()
        meta["parameters"] = {}
        response_list.append(meta)
    return response_list


@router.get(
    "/api/v1/detection/summary",
    response_model=DetectionSummaryResponse,
    summary="Detection telemetry and incident summary",
    description="Aggregated overview of incident statuses, severity distribution, and targeted services."
)
def get_summary(db: Session = Depends(get_db)):
    """Fetch high-level SOC incident summary."""
    return get_detection_summary(db)
