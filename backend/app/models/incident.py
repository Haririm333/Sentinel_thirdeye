"""
SQLAlchemy Model for Security Incidents
Stores security incidents generated by the deterministic detection engine.
"""

from datetime import datetime, timezone
from sqlalchemy import (
    Column, Integer, BigInteger, String, Text, DateTime, JSON, Index
)
from sentinel.backend.app.models.base import Base


class Incident(Base):
    """
    Security incident record generated when an API activity event violates security rules.
    Maintains correlated event references, explainable evidence, risk score, and triage status.
    """
    __tablename__ = "incidents"

    id = Column(BigInteger().with_variant(Integer, "sqlite"), primary_key=True, autoincrement=True)
    
    # Unique incident UUID
    incident_id = Column(String(64), unique=True, index=True, nullable=False)
    
    # Rule identification
    rule_id = Column(String(50), index=True, nullable=False)
    rule_name = Column(String(100), nullable=False)
    
    # Classification & Scoring
    severity = Column(String(20), index=True, nullable=False)  # LOW, MEDIUM, HIGH, CRITICAL
    risk_score = Column(Integer, index=True, nullable=False)    # 0 to 100
    
    # Lifecycle status: OPEN, INVESTIGATING, RESOLVED, FALSE_POSITIVE
    status = Column(String(20), index=True, default="OPEN", nullable=False)
    
    # Entity under observation
    service_identity = Column(String(100), index=True, nullable=False)
    
    # Correlated event tracking
    related_event_ids = Column(JSON, nullable=False, default=list)
    
    # Target resource metadata (sanitized)
    resource_type = Column(String(100), nullable=True)
    resource_id = Column(String(255), nullable=True)
    
    # Explainable narrative and structured evidence
    explanation = Column(Text, nullable=False)
    evidence = Column(JSON, nullable=False, default=dict)
    
    # Temporal tracking (UTC)
    created_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        index=True,
        nullable=False
    )
    updated_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        index=True,
        nullable=False
    )

    __table_args__ = (
        Index("ix_incidents_rule_service_status", "rule_id", "service_identity", "status"),
        Index("ix_incidents_created_severity", "created_at", "severity"),
    )

    def __repr__(self) -> str:
        return (
            f"<Incident(incident_id='{self.incident_id}', rule_id='{self.rule_id}', "
            f"severity='{self.severity}', score={self.risk_score}, status='{self.status}')>"
        )
